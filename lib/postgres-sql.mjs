// The domain services keep their tested synchronous repository contract.
// SQL and data are sent to a PostgreSQL connection owned by a worker thread.
export function splitSql(source){
  const statements=[];let start=0,quote=null;
  for(let i=0;i<source.length;i++){
    const char=source[i];
    if(quote){if(char===quote){if(source[i+1]===quote)i++;else quote=null;}continue;}
    if(char==="'"||char==='"'){quote=char;continue;}
    if(char===';'){if(source.slice(start,i).trim())statements.push(source.slice(start,i).trim());start=i+1;}
  }
  if(source.slice(start).trim())statements.push(source.slice(start).trim());return statements;
}
export function postgresSql(source,parameters=[]){
  const named=parameters.length===1&&parameters[0]&&typeof parameters[0]==='object'&&!Array.isArray(parameters[0])&&!(parameters[0] instanceof Uint8Array);
  const positional=parameters.length===1&&Array.isArray(parameters[0])?parameters[0]:parameters;
  const args=[];let result='',quote=null,index=0;
  for(let i=0;i<source.length;){
    const char=source[i];
    if(quote){result+=char;i++;if(char===quote){if(source[i]===quote){result+=source[i++];}else quote=null;}continue;}
    if(char==='"'){
      let end=i+1;while(end<source.length){if(source[end]==='"'){if(source[end+1]==='"'){end+=2;continue;}break;}end++;}
      const identifier=source.slice(i+1,end).replaceAll('""','"'),lower=identifier.toLowerCase();
      result+=lower==='sqlite_master'||lower==='sqlite_schema'?'"_academy_schema"':lower==='rowid'?'"_academy_rowid"':source.slice(i,end+1);i=end+1;continue;
    }
    if(char==="'"){quote=char;result+=char;i++;continue;}
    if(char==='?'||char==='@'&&/[a-zA-Z_]/.test(source[i+1]||'')){
      let value;
      if(char==='?'){if(named)throw new Error('Não misture parâmetros nomeados e posicionais.');value=positional[index++];i++;}
      else{const match=source.slice(i+1).match(/^[a-zA-Z_][a-zA-Z0-9_]*/)[0];if(!named||!Object.hasOwn(parameters[0],match))throw new Error('Parâmetro nomeado ausente: '+match);value=parameters[0][match];i+=match.length+1;}
      if(value===undefined)throw new Error('Parâmetro SQL ausente.');args.push(value);result+='$'+args.length;continue;
    }
    const token=source.slice(i).match(/^[a-zA-Z_][a-zA-Z0-9_]*/)?.[0];
    if(token){
      const lower=token.toLowerCase();
      result+=lower==='user'?'"user"':lower==='rowid'?'_academy_rowid':lower==='sqlite_master'||lower==='sqlite_schema'?'_academy_schema':/[a-z][A-Z]/.test(token)?'"'+token+'"':token;
      i+=token.length;continue;
    }
    result+=char;i++;
  }
  if(!named&&index<positional.length)throw new Error('A consulta recebeu parâmetros a mais.');
  const ignored=/^INSERT\s+OR\s+IGNORE\s+/i.test(result);
  if(ignored){result=result.replace(/^INSERT\s+OR\s+IGNORE\s+/i,'INSERT ');const returning=result.search(/\bRETURNING\b/i);result=returning<0?result+' ON CONFLICT DO NOTHING':result.slice(0,returning)+' ON CONFLICT DO NOTHING '+result.slice(returning);}
  return {sql:result,params:args};
}
export function postgresDdl(source){
  let {sql}=postgresSql(source);
  const tokens=sql.match(/'(?:''|[^'])*'|"(?:""|[^"])*"|[a-zA-Z_][a-zA-Z0-9_]*|./gs)||[];
  sql=tokens.map(token=>/^['"]/.test(token)?token:/^INTEGER$/i.test(token)?'BIGINT':/^DATE$/i.test(token)?'TIMESTAMPTZ':/^BLOB$/i.test(token)?'BYTEA':/^REAL$/i.test(token)?'DOUBLE PRECISION':/^AUTOINCREMENT$/i.test(token)?'GENERATED BY DEFAULT AS IDENTITY':token).join('');
  // AUTOINCREMENT follows PRIMARY KEY in SQLite and precedes it in Postgres.
  sql=sql.replace(/BIGINT\s+PRIMARY KEY\s+GENERATED BY DEFAULT AS IDENTITY/gi,'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
  if(/^CREATE TABLE\b/i.test(sql)){
    const position=sql.indexOf('(');sql=sql.slice(0,position+1)+'_academy_rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,'+sql.slice(position+1);
  }
  return sql;
}
