import {test} from 'node:test';
import assert from 'node:assert/strict';
import {postgresSql,postgresDdl,splitSql} from '../lib/postgres-sql.mjs';
import {encodeValue,decodeValue} from '../lib/postgres-codec.mjs';
test('consultas PostgreSQL mantêm valores separados do SQL e preservam literais',()=>{
  const query=postgresSql("SELECT userId FROM account JOIN user ON user.id=account.userId WHERE providerId=? AND scope='? @id user'",['google']);
  assert.equal(query.sql,`SELECT "userId" FROM account JOIN "user" ON "user".id=account."userId" WHERE "providerId"=$1 AND scope='? @id user'`);assert.deepEqual(query.params,['google']);
  const named=postgresSql('SELECT @id,@id',[{id:'value'}]);assert.deepEqual(named.params,['value','value']);assert.throws(()=>postgresSql('SELECT @id,?',[{id:'value'}]),/misture/);
});
test('metadados e DDL preservam restrições e usam tipos reais do PostgreSQL',()=>{
  const ddl=postgresDdl("CREATE TABLE example(id TEXT PRIMARY KEY,bytes BLOB,at DATE,n INTEGER,role TEXT CHECK(role IN ('admin','seller')))");
  assert.match(ddl,/bytes BYTEA,at TIMESTAMPTZ,n BIGINT/);assert.match(ddl,/_academy_rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE/);assert.match(ddl,/role IN \('admin','seller'\)/);
  assert.match(postgresDdl('CREATE TABLE messages(sequence INTEGER PRIMARY KEY AUTOINCREMENT)'),/sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/);
  assert.equal(postgresSql('INSERT OR IGNORE INTO example(id) VALUES(?)',['id']).sql,'INSERT INTO example(id) VALUES($1) ON CONFLICT DO NOTHING');
  assert.deepEqual(splitSql("SELECT ';'; SELECT 'it''s fine';"),["SELECT ';'","SELECT 'it''s fine'"]);
});
test('transporte do banco preserva arquivos binários, inteiros e datas',()=>{
  const value={bytes:Buffer.from([0,255,1,19]),at:new Date('2026-10-12T10:00:00Z'),id:123n,rows:[{name:'João'}]};
  assert.deepEqual(decodeValue(JSON.parse(JSON.stringify(encodeValue(value)))),value);
});
